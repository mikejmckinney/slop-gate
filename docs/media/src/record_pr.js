// Drives headed Chromium through one scene of demo PR #11 while screenrec.sh
// records the screen. Writes <scene>.marks.json: epoch seconds of the moments
// encode.py cuts at (screenrec.sh rewrites them as offsets into the video).
//   node record_pr.js <scene> <outdir>    scenes: blocked, diff, fixed, footer
//   env: PR (default 11), FIX_SHA (diff), COMMENT_TEXT (footer)
const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');

const REPO = 'https://github.com/mikejmckinney/slop-gate';
const PR = Number(process.env.PR || 11);
const W = 1280, H = 900;
const marks = {};
const mark = name => { marks[name] = Date.now() / 1000; };

async function smoothTo(page, y, ms = 1200) {
  await page.evaluate(([target, dur]) => new Promise(done => {
    const start = window.scrollY, t0 = performance.now();
    const ease = t => (t < 0.5 ? 2 * t * t : 1 - (-2 * t + 2) ** 2 / 2);
    function step(now) {
      const k = Math.min(1, (now - t0) / dur);
      window.scrollTo(0, start + (target - start) * ease(k));
      if (k < 1) requestAnimationFrame(step);
      else done();
    }
    requestAnimationFrame(step);
  }), [y, ms]);
}

// Page y that puts the first matching element `offset` px below the top.
async function topOf(page, selector, text, offset) {
  return page.evaluate(([sel, txt, off]) => {
    const el = [...document.querySelectorAll(sel)].find(e => e.textContent.includes(txt));
    if (!el) throw new Error(`no ${sel} containing "${txt}"`);
    return Math.max(0, el.getBoundingClientRect().top + window.scrollY - off);
  }, [selector, text, offset]);
}

const scenes = {
  // The report as it first lands: blocked, with a fix for every row.
  async blocked(page) {
    await page.goto(`${REPO}/pull/${PR}`, { waitUntil: 'load' });
    await page.waitForTimeout(600);
    mark('ready');
    await page.waitForTimeout(2000);
    await smoothTo(page, await topOf(page, '.markdown-body h2', 'slop-gate:', 120), 1400);
    await page.waitForTimeout(2400);
    await smoothTo(page, await topOf(page, '.markdown-body h3', 'prose', 40), 1500);
    await page.waitForTimeout(2600);
    await smoothTo(page, await topOf(page, '.markdown-body h3', 'ruff', 40), 1200);
    await page.waitForTimeout(2400);
  },
  // The fix commit's diff: the flagged lines out, plain ones in.
  async diff(page) {
    if (!process.env.FIX_SHA) throw new Error('set FIX_SHA to the fix commit');
    await page.goto(`${REPO}/pull/${PR}/commits/${process.env.FIX_SHA}`, { waitUntil: 'load' });
    await page.waitForTimeout(1500);
    mark('ready');
    await page.waitForTimeout(2000);
    await smoothTo(page, 330, 1200);
    await page.waitForTimeout(2500);
    await smoothTo(page, 900, 1600);
    await page.waitForTimeout(2500);
  },
  // After the push: the same comment, rewritten, then the green fix commit.
  async fixed(page) {
    await page.goto(`${REPO}/pull/${PR}`, { waitUntil: 'load' });
    await page.waitForTimeout(600);
    mark('ready');
    await page.waitForTimeout(1600);
    await smoothTo(page, await topOf(page, '.markdown-body h2', 'slop-gate:', 330), 1400);
    await page.waitForTimeout(3200);
    mark('passed_end');
    await smoothTo(page, await topOf(page, 'a', 'Rewrite the troubleshooting', 420), 1600);
    await page.waitForTimeout(2600);
  },
  // A comment posted from a cloud session arrives with a tool footer, and the
  // footer workflow removes it. Post the comment, then run this at once; it
  // reloads until the footer is gone.
  async footer(page) {
    const needle = process.env.COMMENT_TEXT;
    if (!needle) throw new Error('set COMMENT_TEXT to the start of the new comment');
    const footer = 'Generated by';
    const comment = () => page.locator('.timeline-comment', { hasText: needle }).last();
    const show = async () => {
      await page.waitForTimeout(800);
      await comment().scrollIntoViewIfNeeded();
      await page.evaluate(() => window.scrollBy(0, 220));
    };
    await page.goto(`${REPO}/pull/${PR}`, { waitUntil: 'load' });
    await show();
    if (!(await comment().textContent()).includes(footer)) throw new Error('the footer was already gone');
    mark('ready');
    await page.waitForTimeout(3000);
    for (let i = 0; i < 30 && !marks.stripped; i++) {
      await page.reload({ waitUntil: 'load' });
      await show();
      if ((await comment().textContent()).includes(footer)) await page.waitForTimeout(1500);
      else mark('stripped');
    }
    if (!marks.stripped) throw new Error('the footer was still there after 30 reloads');
    await page.waitForTimeout(3000);
  },
};

(async () => {
  const [scene, outdir] = process.argv.slice(2);
  if (!scenes[scene]) throw new Error(`unknown scene "${scene}"; use ${Object.keys(scenes).join(', ')}`);
  fs.mkdirSync(outdir, { recursive: true });
  // Headed, filling the Xvfb screen that ffmpeg records. The browser's toolbar
  // stays in the shot, so the URL is visible.
  const browser = await chromium.launch({
    headless: false,
    args: [`--window-size=${W},${H}`, '--window-position=0,0', '--force-dark-mode'],
  });
  const context = await browser.newContext({ viewport: null, colorScheme: 'dark' });
  // Logged-out GitHub renders in light mode unless this cookie asks for dark.
  const theme = { color_mode: 'dark', light_theme: { name: 'light', color_mode: 'light' }, dark_theme: { name: 'dark', color_mode: 'dark' } };
  await context.addCookies([{ name: 'color_mode', domain: '.github.com', path: '/', value: encodeURIComponent(JSON.stringify(theme)) }]);
  const page = await context.newPage();
  await scenes[scene](page);
  mark('end');
  await browser.close();
  fs.writeFileSync(path.join(outdir, `${scene}.marks.json`), JSON.stringify(marks));
  console.log(scene, JSON.stringify(marks));
})().catch(e => { console.error(`record_pr.js: ${e.message}`); process.exit(1); });
