"""Draft a media manifest from the assets already in a repo.

The draft records what exists today. Review it: anything the generator can't
know (which tracks loop, the intended palette size) is left as a comment.
"""

from __future__ import annotations

import statistics
from collections import defaultdict
from pathlib import Path, PurePosixPath

import numpy as np
from PIL import Image

from . import media
from .gitdiff import all_files


def _image_facts(path: Path) -> dict | None:
    try:
        with Image.open(path) as im:
            im.load()
            rgba = np.asarray(im.convert("RGBA"))
    except Exception:  # noqa: BLE001 - an unreadable file is reported by the check, not the draft
        return None
    alpha = rgba[..., 3]
    visible = rgba[alpha > 0]
    colors = len(np.unique(visible.view(np.uint32))) if len(visible) else 0
    return {
        "size": f"{rgba.shape[1]}x{rgba.shape[0]}",
        "colors": colors,
        "transparent": bool((alpha < 255).any()),
        "soft_alpha": bool(((alpha > 0) & (alpha < 255)).any()),
    }


def _audio_facts(path: Path) -> dict | None:
    try:
        info = media._probe(path)
    except RuntimeError:
        return None
    lufs, _ = media._loudness(path)
    return {**info, "lufs": lufs}


def draft(repo: Path) -> str:
    groups: dict[tuple[str, str, str], list[str]] = defaultdict(list)
    for rel in sorted(all_files(repo)):
        p = PurePosixPath(rel)
        ext = p.suffix.lower()
        kind = "image" if ext in media.IMAGE_EXTS else "audio" if ext in media.AUDIO_EXTS else None
        if kind:
            groups[(str(p.parent), kind, ext)].append(rel)

    lines = [
        "# Draft media manifest generated by `python -m slopgate media-init`.",
        "# Values describe the files as they are today. Keep the ones that are",
        "# intentional, delete the rest, and fill in the commented hints.",
        "media:",
        "  rules:",
    ]
    for (folder, kind, ext), files in sorted(groups.items()):
        glob = f"{folder}/*{ext}" if folder != "." else f"*{ext}"
        lines.append(f'    - glob: "{glob}"  # {len(files)} file(s)')
        if kind == "image":
            facts = [f for f in (_image_facts(repo / r) for r in files) if f]
            if not facts:
                continue
            sizes = {f["size"] for f in facts}
            if len(sizes) == 1:
                lines.append(f'      size: "{sizes.pop()}"')
            max_colors = max(f["colors"] for f in facts)
            if max_colors <= 256 and not any(f["soft_alpha"] for f in facts):
                lines.append(f"      max_colors: {max_colors}  # looks like pixel art; set your palette size")
                lines.append("      pixel_art: true")
            if all(f["transparent"] for f in facts):
                lines.append("      alpha: required")
            lines.append("      # tileable: true  # for textures that repeat")
        else:
            facts = [f for f in (_audio_facts(repo / r) for r in files) if f]
            if not facts:
                continue
            rates = {f["sample_rate"] for f in facts}
            if len(rates) == 1:
                lines.append(f"      sample_rate: {rates.pop()}")
            measured = [f["lufs"] for f in facts if f["lufs"] is not None and f["duration"] >= 1.0]
            if measured:
                lines.append(
                    f"      # loudness_lufs: {round(statistics.median(measured))}  "
                    f"# median today; common targets: -16 music, -14 to -18 SFX"
                )
            lines.append("      # loop: true  # set for music or ambience that repeats")
    return "\n".join(lines) + "\n"
