@unittest.skipUnless(HAS_VALE, "vale not installed")
class EndToEndTests(unittest.TestCase):
    def setUp(self):
        self.repo = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.repo)
        git(self.repo, "init", "-q", "-b", "main")
        git(self.repo, "config", "user.email", "t@example.com")
        git(self.repo, "config", "user.name", "t")
        # Pre-existing debt on main must not block a PR that doesn't touch it.
        (self.repo / "README.md").write_text("# Demo\n\nIt's important to note that this is old text.\n")
        git(self.repo, "add", ".")
        git(self.repo, "commit", "-qm", "base")
        git(self.repo, "checkout", "-qb", "feature")
        with (self.repo / "README.md").open("a") as f:
            f.write("\nThis isn't just a demo, it's a platform.\n")
        (self.repo / "app.py").write_text(
            "import os\n\n\ndef run():\n    try:\n        return 1\n    except Exception:\n        pass\n"
        )
        git(self.repo, "add", ".")
        git(self.repo, "commit", "-qm", "feature")

    def run_cli(self, *extra):
        out, err = io.StringIO(), io.StringIO()
        report = self.repo / "report.json"
        with redirect_stdout(out), redirect_stderr(err):
            code = main(
                [
                    "check",
                    "--repo",
                    str(self.repo),
                    "--base",
                    "main",
                    "--head",
                    "feature",
                    "--only",
                    "prose,code",
                    "--report-json",
                    str(report),
                    *extra,
                ]
            )
        return code, json.loads(report.read_text()), out.getvalue()

    def test_only_changed_lines_are_reported_and_errors_block(self):
        code, findings, report = self.run_cli()
        self.assertEqual(code, 1)
        rules = {(f["path"], f["rule"]) for f in findings}
        self.assertIn(("README.md", "SlopGate.ContrastFormula"), rules)
        self.assertNotIn(("README.md", "SlopGate.HedgingPreambles"), rules)  # untouched line
        self.assertIn(("app.py", "F401"), rules)
        self.assertIn(("app.py", "S110"), rules)
        self.assertIn("**Fix:**", report)

    def test_override_can_turn_a_rule_off(self):
        (self.repo / ".slop-gate.yml").write_text(
            "overrides:\n  SlopGate.ContrastFormula: 'off'\n  F401: warning\n  S110: warning\n"
            "  BLE001: warning\n  format: 'off'\n"
        )
        code, findings, _ = self.run_cli()
        self.assertEqual(code, 0, findings)
        self.assertNotIn("SlopGate.ContrastFormula", {f["rule"] for f in findings})


@unittest.skipUnless(HAS_VALE, "vale not installed")
class FormatScopeTests(unittest.TestCase):
    """An edit inside an old, unformatted file only warns unless scope is `changed`."""

    def setUp(self):
        self.repo = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.repo)
        git(self.repo, "init", "-q", "-b", "main")
        git(self.repo, "config", "user.email", "t@example.com")
        git(self.repo, "config", "user.name", "t")
        (self.repo / "old.py").write_text("x = {'a':1}\ny = [1,2]\n")
        git(self.repo, "add", ".")
        git(self.repo, "commit", "-qm", "base")
        git(self.repo, "checkout", "-qb", "feature")
        (self.repo / "old.py").write_text("x = {'a':1}\ny = [1,2,3]\n")
        git(self.repo, "commit", "-qam", "edit")

    def format_severity(self, config=""):
        if config:
            (self.repo / ".slop-gate.yml").write_text(config)
        report = self.repo / "r.json"
        with redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()):
            main(
                [
                    "check",
                    "--repo",
                    str(self.repo),
                    "--base",
                    "main",
                    "--head",
                    "feature",
                    "--only",
                    "code",
                    "--report-json",
                    str(report),
                ]
            )
        return {f["severity"] for f in json.loads(report.read_text()) if f["rule"] == "format"}

    def test_default_scope_warns_on_edits(self):
        self.assertEqual(self.format_severity(), {"warning"})

    def test_changed_scope_blocks_on_edits(self):
        self.assertEqual(self.format_severity("code:\n  ruff_format_scope: changed\n"), {"error"})


@unittest.skipUnless(HAS_VALE, "vale not installed")
class UnreadableFileTests(unittest.TestCase):
    """A file Vale can't parse is reported; it must not stop the other files."""

    def setUp(self):
        self.repo = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.repo)
        (self.repo / "bad.md").write_text("---\ndescription: Three forms: one, two\n---\n\nText.\n")
        (self.repo / "slop.md").write_text("It's important to note that the cache is per-process.\n")

    def test_bad_front_matter_is_a_warning_and_other_files_still_run(self):
        from slopgate.prose import run_vale

        found = {
            (f.path, f.rule, f.severity)
            for f in run_vale(self.repo, ROOT / ".vale.ini", ["bad.md", "slop.md"])
        }
        self.assertIn(("bad.md", "vale-unreadable", "warning"), found)
        self.assertIn(("slop.md", "SlopGate.HedgingPreambles", "error"), found)

    def test_broken_config_is_still_fatal(self):
        from slopgate.prose import run_vale

        ini = self.repo / "broken.ini"
        ini.write_text("StylesPath = does-not-exist\n[*.md]\nBasedOnStyles = Nope\n")
        with self.assertRaises(RuntimeError):
            run_vale(self.repo, ini, ["slop.md"])

    def test_pr_mode_keeps_the_warning_when_only_the_body_changed(self):
        # The parse error is on line 1, which the PR doesn't touch; the warning
        # must survive changed-line filtering or the PR passes unchecked prose.
        git(self.repo, "init", "-q", "-b", "main")
        git(self.repo, "config", "user.email", "t@example.com")
        git(self.repo, "config", "user.name", "t")
        git(self.repo, "add", "bad.md")
        git(self.repo, "commit", "-qm", "base")
        git(self.repo, "checkout", "-qb", "feature")
        with (self.repo / "bad.md").open("a") as f:
            f.write("\nIt's important to note that the cache is per-process.\n")
        git(self.repo, "commit", "-qam", "edit body")
        report = self.repo / "r.json"
        with redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()):
            main(
                [
                    "check",
                    "--repo",
                    str(self.repo),
                    "--base",
                    "main",
                    "--head",
                    "feature",
                    "--only",
                    "prose",
                    "--report-json",
                    str(report),
                ]
            )
        findings = json.loads(report.read_text())
        self.assertEqual(
            [(f["path"], f["rule"], f["line"]) for f in findings], [("bad.md", "vale-unreadable", None)]
        )


@unittest.skipUnless(HAS_VALE, "vale not installed")
class ValeFollowUpTests(unittest.TestCase):
    """Issue #7: path matching, bisecting, the AI rule in prose, and the hint."""

    def setUp(self):
        self.repo = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.repo)

    def test_error_is_attributed_only_to_the_exact_file(self):
        import subprocess as sp

        from slopgate.prose import _file_error

        error = json.dumps({"Path": "docs/data.md", "Line": 2, "Text": "yaml: bad"})
        result = sp.CompletedProcess([], 2, stdout="{}", stderr=error)
        self.assertIsNone(_file_error(result, self.repo, "a.md"))
        self.assertIsNone(_file_error(result, self.repo, "data.md"))
        self.assertEqual(_file_error(result, self.repo, "docs/data.md")["Line"], 2)

    def test_failed_batch_is_bisected(self):
        import slopgate.prose as prose_mod

        names = [f"f{i:02d}.md" for i in range(64)]
        for n in names:
            (self.repo / n).write_text("Plain text.\n")
        (self.repo / "f37.md").write_text("---\ndescription: Three forms: one, two\n---\n\nText.\n")
        (self.repo / "f05.md").write_text("It's important to note that the cache is per-process.\n")
        calls = []
        real_run = prose_mod.subprocess.run

        def counting_run(*a, **kw):
            calls.append(1)
            return real_run(*a, **kw)

        with unittest.mock.patch.object(prose_mod.subprocess, "run", counting_run):
            found = prose_mod.run_vale(self.repo, ROOT / ".vale.ini", names)
        rules = {(f.path, f.rule) for f in found}
        self.assertIn(("f37.md", "vale-unreadable"), rules)
        self.assertIn(("f05.md", "SlopGate.HedgingPreambles"), rules)
        # One full run plus two runs per halving step: 1 + 2 * log2(64) = 13.
        self.assertLessEqual(len(calls), 13)

    def test_front_matter_hint_only_for_yaml_errors(self):
        from slopgate.prose import _unreadable

        yaml_fix = _unreadable("prose", "a.md", {"Line": 2, "Text": "yaml: line 2: mapping values"}).fix
        other = _unreadable("prose", "a.md", {"Line": 9, "Text": "unexpected token " + "x" * 400})
        self.assertIn("front matter", yaml_fix)
        self.assertNotIn("front matter", other.fix)
        self.assertLess(len(other.message), 300)

    def test_pr_body_with_broken_front_matter_warns_instead_of_failing(self):
        body = "---\ntitle: Fix: retries\n---\n\nAdds retry.\n"
        found = check_pr(ROOT / ".vale.ini", "Add retry", body)
        self.assertIn(
            ("PR description", "vale-unreadable", "warning"), {(f.path, f.rule, f.severity) for f in found}
        )

    def test_ai_rule_in_prose(self):
        from slopgate.prose import run_vale

        should = [
            "As an AI language model, I cannot browse.",
            "As an AI model, I lack access.",
            "As an AI chatbot, I suggest retrying.",
            "As an AI developed by a lab, I cannot say.",
            "As an AI, I recommend a retry.",
        ]
        should_not = [
            "Configure API Management as an AI Gateway.",
            "We run the cluster as an AI platform for the team.",
            "Register the service as an AI endpoint.",
        ]
        for i, line in enumerate(should + should_not):
            (self.repo / f"t{i}.md").write_text(line + "\n")
        found = run_vale(self.repo, ROOT / ".vale.ini", [f"t{i}.md" for i in range(len(should + should_not))])
        hit = {f.path for f in found if f.rule == "SlopGate.AssistantResidue"}
        self.assertEqual(hit, {f"t{i}.md" for i in range(len(should))})


