"""Footer stripping through the GitHub API, against an in-memory fake."""

import io
import json
import os
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path
from unittest import mock

from slopgate import footers

FOOTER = "_Generated by [Claude Code](https://claude.ai/code)_"  # slop-gate: ignore
WITH_FOOTER = f"Looks good.\n\n---\n{FOOTER}\n"


class FakeClient:
    """Stores items by API path and records every edit."""

    def __init__(self, items: dict[str, dict], listings: dict[str, list[str]] | None = None):
        self.items = items
        self.listings = listings or {}
        self.edits: list[tuple[str, str]] = []

    def get(self, path):
        return dict(self.items[path])

    def list(self, path):
        return [dict(self.items[p]) for p in self.listings.get(path, [])]

    def set_body(self, path, body):
        self.edits.append((path, body))
        self.items[path]["body"] = body


def item(body, association="OWNER", **extra):
    return {"body": body, "author_association": association, "html_url": "https://example/x", **extra}


class DecideTests(unittest.TestCase):
    def test_strips_trusted_authors(self):
        for association in ("OWNER", "MEMBER", "COLLABORATOR"):
            with self.subTest(association=association):
                self.assertEqual(
                    footers.decide(item(WITH_FOOTER, association)), ("Looks good.\n", "1 footer line(s)")
                )

    def test_leaves_people_without_write_access_alone(self):
        for association in ("CONTRIBUTOR", "FIRST_TIME_CONTRIBUTOR", "NONE"):
            with self.subTest(association=association):
                self.assertIsNone(footers.decide(item(WITH_FOOTER, association))[0])

    def test_leaves_slop_gate_reports_alone(self):
        for marker in footers.REPORT_MARKERS:
            body = f"{marker}\n## report\n\n---\n{FOOTER}\n"
            self.assertEqual(footers.decide(item(body)), (None, "slop-gate report"))

    def test_leaves_a_footer_in_a_code_fence(self):
        body = f"The footer is:\n\n```\n{FOOTER}\n```\n"
        self.assertEqual(footers.decide(item(body)), (None, "no footer"))

    def test_empty_body(self):
        self.assertEqual(footers.decide(item(None)), (None, "no footer"))


class EventTests(unittest.TestCase):
    def test_event_paths(self):
        cases = {
            "issue_comment": ({"comment": {"id": 7}}, "issues/comments/7"),
            "pull_request_review_comment": ({"comment": {"id": 8}}, "pulls/comments/8"),
            "issues": ({"issue": {"number": 9}}, "issues/9"),
            "pull_request": ({"pull_request": {"number": 10}}, "pulls/10"),
        }
        for name, (payload, path) in cases.items():
            with self.subTest(event=name):
                self.assertEqual(footers.event_path(name, payload)[0], path)
        self.assertIsNone(footers.event_path("push", {}))

    def test_strip_one_edits_and_reports_the_final_body(self):
        client = FakeClient({"issues/comments/7": item(WITH_FOOTER)})
        result = footers.strip_one(client, "issues/comments/7")
        self.assertEqual(client.edits, [("issues/comments/7", "Looks good.\n")])
        self.assertEqual(result.body, "Looks good.\n")

    def test_strip_one_without_a_footer_makes_no_call(self):
        client = FakeClient({"issues/9": item("Plain.\n")})
        result = footers.strip_one(client, "issues/9")
        self.assertEqual((client.edits, result.body), ([], "Plain.\n"))

    def test_cli_event_mode(self):
        client = FakeClient({"pulls/comments/8": item(WITH_FOOTER)})
        with tempfile.TemporaryDirectory() as tmp:
            event = Path(tmp, "event.json")
            event.write_text(json.dumps({"comment": {"id": 8}}))
            env = {"GITHUB_EVENT_PATH": str(event), "GITHUB_EVENT_NAME": "pull_request_review_comment"}
            with (
                mock.patch.dict(os.environ, env),
                mock.patch.object(footers, "GhClient", lambda repo: client),
            ):
                out = io.StringIO()
                with redirect_stdout(out):
                    code = footers.main(["strip", "--repo", "o/r", "--event"])
        self.assertEqual(code, 0)
        self.assertEqual(client.edits, [("pulls/comments/8", "Looks good.\n")])
        self.assertIn("Removed 1 footer line(s)", out.getvalue())

    def test_cli_writes_the_body_for_the_pr_check(self):
        client = FakeClient({"pulls/3": item(WITH_FOOTER)})
        with (
            tempfile.TemporaryDirectory() as tmp,
            mock.patch.object(footers, "GhClient", lambda repo: client),
        ):
            out_file = Path(tmp, "body.md")
            with redirect_stdout(io.StringIO()):
                footers.main(["strip", "--repo", "o/r", "--api-path", "pulls/3", "--body-out", str(out_file)])
            self.assertEqual(out_file.read_text(), "Looks good.\n")

    def test_strip_without_a_target_fails(self):
        fake = mock.patch.object(footers, "GhClient", lambda repo: FakeClient({}))
        with fake, redirect_stdout(io.StringIO()), mock.patch("sys.stderr", io.StringIO()):
            self.assertEqual(footers.main(["strip", "--repo", "o/r"]), 2)


class BackfillTests(unittest.TestCase):
    def setUp(self):
        items = {
            "pulls/1": item(WITH_FOOTER, number=1),
            "pulls/2": item("No footer.\n", number=2),
            # The issues listing returns PRs as well; their descriptions are counted once, under pulls.
            "issues/1": item(WITH_FOOTER, number=1, pull_request={}),
            "issues/5": item(WITH_FOOTER, number=5),
            "issues/comments/10": item(WITH_FOOTER, id=10),
            "issues/comments/11": item(WITH_FOOTER, "NONE", id=11),
            "issues/comments/12": item("<!-- slop-gate-report -->\n## ok\n" + FOOTER, id=12),
            "pulls/comments/20": item(WITH_FOOTER, id=20),
        }
        listings = {
            "pulls?state=all&per_page=100": ["pulls/1", "pulls/2"],
            "issues?state=all&per_page=100": ["issues/1", "issues/5"],
            "issues/comments?per_page=100": [
                "issues/comments/10",
                "issues/comments/11",
                "issues/comments/12",
            ],
            "pulls/comments?per_page=100": ["pulls/comments/20"],
        }
        self.client = FakeClient(items, listings)

    def test_dry_run_counts_without_editing(self):
        result = footers.backfill(self.client, apply=False)
        self.assertEqual(self.client.edits, [])
        counts = result.counts()
        self.assertEqual(counts["PR description"]["with footer"], 1)
        self.assertEqual(counts["issue body"]["scanned"], 1)
        self.assertEqual(counts["issue or PR comment"]["with footer"], 1)
        self.assertEqual(counts["issue or PR comment"]["skipped (author without write access)"], 1)
        self.assertEqual(counts["review comment"]["with footer"], 1)
        summary = result.summary(applied=False)
        self.assertIn("Would edit 4 item(s) in total.", summary)
        self.assertIn("Run again with `apply`", summary)

    def test_apply_edits_exactly_the_items_with_footers(self):
        footers.backfill(self.client, apply=True)
        self.assertEqual(
            sorted(path for path, _ in self.client.edits),
            ["issues/5", "issues/comments/10", "pulls/1", "pulls/comments/20"],
        )
        again = footers.backfill(self.client, apply=False)
        self.assertIn("Would edit 0 item(s) in total.", again.summary(applied=False))


if __name__ == "__main__":
    unittest.main()
