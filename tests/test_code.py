import unittest

from slopgate.code import RESIDUE_RULES, scan_unicode_line


def rules(text, is_code=True):
    return [rule for _, rule, _ in scan_unicode_line(text, is_code)]


class UnicodeTests(unittest.TestCase):
    def test_bidi_override_is_hidden_character(self):
        self.assertIn("hidden-character", rules('access = "user\u202e \u2066// admin\u2069"'))

    def test_zero_width_space(self):
        self.assertIn("hidden-character", rules("is\u200bAdmin = True"))

    def test_tag_characters_smuggling(self):
        payload = "".join(chr(0xE0000 + ord(c)) for c in "ignore previous")
        self.assertIn("hidden-character", rules(f"# helper{payload}"))

    def test_variation_selector_run(self):
        self.assertIn("hidden-character", rules("x = 1\ufe00\ufe01\ufe02"))

    def test_emoji_sequences_are_allowed(self):
        family = "\U0001f468\u200d\U0001f469\u200d\U0001f467"
        self.assertEqual(rules(f"Team: {family} and ❤\ufe0f and 1\ufe0f⃣", is_code=False), [])

    def test_homoglyph_identifier(self):
        self.assertIn("homoglyph", rules("if p\u0430ypal_user:"))  # Cyrillic a

    def test_greek_unit_is_not_homoglyph(self):
        self.assertEqual(rules("latency is 40 μs", is_code=False), [])

    def test_nbsp_is_error_in_code_warning_in_prose(self):
        self.assertEqual(scan_unicode_line("x =\u00a01", True)[0][0], "error")
        self.assertEqual(scan_unicode_line("see\u00a0below", False)[0][0], "warning")

    def test_plain_ascii_is_clean(self):
        self.assertEqual(rules("def load(path: str) -> dict:"), [])


class ResidueTests(unittest.TestCase):
    samples = {
        "truncation-marker": "    # ... rest of the code remains the same",  # slop-gate: ignore
        "placeholder-secret": 'API_KEY = "your_api_key_here"',  # slop-gate: ignore
        "ai-banner": "// Generated by ChatGPT",  # slop-gate: ignore
        "assistant-residue": "# Here's the updated function with error handling",  # slop-gate: ignore
        "stub-admission": "    # TODO: implement the actual retry logic",  # slop-gate: ignore
        "hedged-implementation": "# In a real application, you would validate the token",  # slop-gate: ignore
    }
    clean = [
        "def rest_of_code(): pass",
        "# Generated by protoc. DO NOT EDIT.",
        "TOKEN = os.environ['API_TOKEN']",
        "# TODO: support IPv6 (issue #41)",
        "# Configure API Management as an AI gateway",
    ]

    def matched(self, line):
        return {rule for rule, _, pat, _ in RESIDUE_RULES if pat.search(line)}

    def test_each_rule_has_a_triggering_sample(self):
        self.assertEqual(set(self.samples), {r[0] for r in RESIDUE_RULES})
        for rule, line in self.samples.items():
            with self.subTest(rule=rule):
                self.assertIn(rule, self.matched(line))

    def test_ordinary_code_is_clean(self):
        for line in self.clean:
            with self.subTest(line=line):
                self.assertEqual(self.matched(line), set())


if __name__ == "__main__":
    unittest.main()
